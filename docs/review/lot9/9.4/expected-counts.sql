-- Lot 9.4 - expected counts for V1/V2, computed independently in SQL for member@mentora.fr.
-- Visible = active AND (Mentora entry OR owned by a coach the member is attached to).
CREATE TEMP VIEW v AS
SELECT e.*
FROM "EXERCISES" e
WHERE e."EXERCISE_IS_ACTIVE"
  AND (e."EXERCISE_COACH_ID" IS NULL
       OR e."EXERCISE_COACH_ID" IN (
            SELECT mc."COACH_ID" FROM "MEMBER_COACHES" mc
            JOIN "MEMBERS" m ON m."MEMBER_ID" = mc."MEMBER_ID"
            JOIN "USERS" u ON u."USER_ID" = m."USER_ID"
            WHERE u."USER_EMAIL" = 'member@mentora.fr'));

SELECT 'V1 visible total' AS check, count(*) AS n FROM v
UNION ALL SELECT 'V2 Pectoraux (primary group)', count(*) FROM v
  WHERE "EXERCISE_PRIMARY_MUSCLE_GROUP_ID" = (SELECT "MUSCLE_GROUP_ID" FROM "MUSCLE_GROUPS" WHERE "MUSCLE_GROUP_NAME" = 'Pectoraux')
UNION ALL SELECT 'V2 Haltères (primary OR secondary)', count(*) FROM v
  WHERE (SELECT "EQUIPMENT_ID" FROM "EQUIPMENT" WHERE "EQUIPMENT_NAME" = 'Haltères') IN ("EXERCISE_PRIMARY_EQUIPMENT_ID", "EXERCISE_SECONDARY_EQUIPMENT_ID")
UNION ALL SELECT 'V2 Sans matériel (primary OR secondary)', count(*) FROM v
  WHERE (SELECT "EQUIPMENT_ID" FROM "EQUIPMENT" WHERE "EQUIPMENT_NAME" = 'Sans matériel') IN ("EXERCISE_PRIMARY_EQUIPMENT_ID", "EXERCISE_SECONDARY_EQUIPMENT_ID")
UNION ALL SELECT 'V2 Banc (primary OR secondary)', count(*) FROM v
  WHERE (SELECT "EQUIPMENT_ID" FROM "EQUIPMENT" WHERE "EQUIPMENT_NAME" = 'Banc') IN ("EXERCISE_PRIMARY_EQUIPMENT_ID", "EXERCISE_SECONDARY_EQUIPMENT_ID")
UNION ALL SELECT 'V2 objective Force', count(*) FROM v
  WHERE "EXERCISE_ID" IN (SELECT "EXERCISE_OBJECTIVE_EXERCISE_ID" FROM "EXERCISE_OBJECTIVES"
                          WHERE "EXERCISE_OBJECTIVE_OBJECTIVE_ID" = (SELECT "OBJECTIVE_ID" FROM "OBJECTIVES" WHERE "OBJECTIVE_NAME" = 'Force'))
UNION ALL SELECT 'V2 level BEGINNER', count(*) FROM v WHERE "EXERCISE_MIN_LEVEL" IN ('BEGINNER')
UNION ALL SELECT 'V2 level INTERMEDIATE (<=)', count(*) FROM v WHERE "EXERCISE_MIN_LEVEL" IN ('BEGINNER', 'INTERMEDIATE')
UNION ALL SELECT 'V2 search squat', count(*) FROM v
  WHERE "EXERCISE_NAME" ILIKE '%squat%' OR "EXERCISE_NAME_EN" ILIKE '%squat%' OR "EXERCISE_SEARCH_TAGS" ILIKE '%squat%'
UNION ALL SELECT 'V2 combined Pectoraux + Haltères', count(*) FROM v
  WHERE "EXERCISE_PRIMARY_MUSCLE_GROUP_ID" = (SELECT "MUSCLE_GROUP_ID" FROM "MUSCLE_GROUPS" WHERE "MUSCLE_GROUP_NAME" = 'Pectoraux')
    AND (SELECT "EQUIPMENT_ID" FROM "EQUIPMENT" WHERE "EQUIPMENT_NAME" = 'Haltères') IN ("EXERCISE_PRIMARY_EQUIPMENT_ID", "EXERCISE_SECONDARY_EQUIPMENT_ID")
UNION ALL SELECT 'V2 combined Force + level INTERMEDIATE', count(*) FROM v
  WHERE "EXERCISE_MIN_LEVEL" IN ('BEGINNER', 'INTERMEDIATE')
    AND "EXERCISE_ID" IN (SELECT "EXERCISE_OBJECTIVE_EXERCISE_ID" FROM "EXERCISE_OBJECTIVES"
                          WHERE "EXERCISE_OBJECTIVE_OBJECTIVE_ID" = (SELECT "OBJECTIVE_ID" FROM "OBJECTIVES" WHERE "OBJECTIVE_NAME" = 'Force'))
ORDER BY 1;

SELECT 'ids' AS k, 'Pectoraux' AS n, "MUSCLE_GROUP_ID"::text AS id FROM "MUSCLE_GROUPS" WHERE "MUSCLE_GROUP_NAME" = 'Pectoraux'
UNION ALL SELECT 'ids', 'Haltères', "EQUIPMENT_ID"::text FROM "EQUIPMENT" WHERE "EQUIPMENT_NAME" = 'Haltères'
UNION ALL SELECT 'ids', 'Sans matériel', "EQUIPMENT_ID"::text FROM "EQUIPMENT" WHERE "EQUIPMENT_NAME" = 'Sans matériel'
UNION ALL SELECT 'ids', 'Banc', "EQUIPMENT_ID"::text FROM "EQUIPMENT" WHERE "EQUIPMENT_NAME" = 'Banc'
UNION ALL SELECT 'ids', 'Force', "OBJECTIVE_ID"::text FROM "OBJECTIVES" WHERE "OBJECTIVE_NAME" = 'Force';
