-- Lot 11.2b cleanup (local DB). Bounded by l11b- names / fixed ids AND created date >= run start.
-- Run start (UTC): 2026-10-04 20:46:22.905787+00
BEGIN;

CREATE TEMP TABLE l11b_counts (step text, tbl text, n bigint);

CREATE TEMP VIEW l11b_now AS
SELECT 'PRODUCTS' AS tbl, count(*) AS n FROM "PRODUCTS" WHERE "PRODUCT_NAME" LIKE 'l11b-%'
UNION ALL SELECT 'SESSION_SLOTS', count(*) FROM "SESSION_SLOTS" WHERE "SESSION_SLOT_ID" IN ('bcdc0a82-98dc-418e-9ef2-c07b0d25a0c3','51a049be-e82c-4ad0-b3f0-6fad3e5b4ad2','bd2033a5-33ad-4489-87fd-708cb6c89fc0','39b9f9c9-382e-4859-b435-ca54e815da43')
UNION ALL SELECT 'SESSIONS', count(*) FROM "SESSIONS" WHERE "SESSION_PRODUCT_ID" IN (SELECT "PRODUCT_ID" FROM "PRODUCTS" WHERE "PRODUCT_NAME" LIKE 'l11b-%')
UNION ALL SELECT 'SESSION_VOUCHERS', count(*) FROM "SESSION_VOUCHERS" WHERE "VOUCHER_PRODUCT_ID" IN (SELECT "PRODUCT_ID" FROM "PRODUCTS" WHERE "PRODUCT_NAME" LIKE 'l11b-%')
UNION ALL SELECT 'ORDERS', count(*) FROM "ORDERS" WHERE "ORDER_ID" IN (SELECT "ORDER_ITEM_ORDER_ID" FROM "ORDER_ITEMS" WHERE "ORDER_ITEM_PRODUCT_NAME" LIKE 'l11b-%')
UNION ALL SELECT 'ORDER_ITEMS', count(*) FROM "ORDER_ITEMS" WHERE "ORDER_ITEM_PRODUCT_NAME" LIKE 'l11b-%'
UNION ALL SELECT 'PROGRAMS', count(*) FROM "PROGRAMS" WHERE "PROGRAM_NAME" = 'l11b-prog'
UNION ALL SELECT 'PROGRAM_SESSIONS', count(*) FROM "PROGRAM_SESSIONS" WHERE "PROGRAM_SESSION_PROGRAM_ID" IN (SELECT "PROGRAM_ID" FROM "PROGRAMS" WHERE "PROGRAM_NAME" = 'l11b-prog')
UNION ALL SELECT 'COACH_PARAMETERS(B)', count(*) FROM "COACH_PARAMETERS" WHERE "COACH_ID" = '11b00000-0000-4000-8000-0000000000b2'
UNION ALL SELECT 'OFFER_PROGRAMS(B)', count(*) FROM "OFFER_PROGRAMS" WHERE "COACH_ID" = '11b00000-0000-4000-8000-0000000000b2'
UNION ALL SELECT 'MEMBER_COACHES(B)', count(*) FROM "MEMBER_COACHES" WHERE "MEMBER_COACH_ID" = '11b00000-0000-4000-8000-0000000000b3'
UNION ALL SELECT 'COACHES(B)', count(*) FROM "COACHES" WHERE "COACH_ID" = '11b00000-0000-4000-8000-0000000000b2'
UNION ALL SELECT 'USERS(B)', count(*) FROM "USERS" WHERE "USER_ID" = '11b00000-0000-4000-8000-0000000000b1';

INSERT INTO l11b_counts SELECT 'before', tbl, n FROM l11b_now;

-- 1. bookings (participants cascade; program-session link and voucher reservation SET NULL)
DELETE FROM "SESSIONS"
WHERE "SESSION_PRODUCT_ID" IN (SELECT "PRODUCT_ID" FROM "PRODUCTS" WHERE "PRODUCT_NAME" LIKE 'l11b-%' AND "PRODUCT_CREATED_DATE" >= '2026-10-04 20:46:22.905787+00')
  AND "SESSION_CREATED_DATE" >= '2026-10-04 20:46:22.905787+00';

-- 2. vouchers
DELETE FROM "SESSION_VOUCHERS"
WHERE "VOUCHER_PRODUCT_ID" IN (SELECT "PRODUCT_ID" FROM "PRODUCTS" WHERE "PRODUCT_NAME" LIKE 'l11b-%' AND "PRODUCT_CREATED_DATE" >= '2026-10-04 20:46:22.905787+00')
  AND "VOUCHER_CREATED_DATE" >= '2026-10-04 20:46:22.905787+00';

-- 3. orders (order items cascade)
DELETE FROM "ORDERS"
WHERE "ORDER_CREATED_DATE" >= '2026-10-04 20:46:22.905787+00'
  AND "ORDER_ID" IN (SELECT "ORDER_ITEM_ORDER_ID" FROM "ORDER_ITEMS" WHERE "ORDER_ITEM_PRODUCT_NAME" LIKE 'l11b-%');

-- 4. coach A fixture slots (coach B slots cascade with coach B)
DELETE FROM "SESSION_SLOTS"
WHERE "SESSION_SLOT_ID" IN ('bcdc0a82-98dc-418e-9ef2-c07b0d25a0c3','51a049be-e82c-4ad0-b3f0-6fad3e5b4ad2','bd2033a5-33ad-4489-87fd-708cb6c89fc0')
  AND "SESSION_SLOT_CREATED_DATE" >= '2026-10-04 20:46:22.905787+00';

-- 5. program (blocks, sessions, circuits, exercises cascade)
DELETE FROM "PROGRAMS"
WHERE "PROGRAM_NAME" = 'l11b-prog' AND "PROGRAM_CREATED_DATE" >= '2026-10-04 20:46:22.905787+00';

-- 6. coach A fixture products
DELETE FROM "PRODUCTS"
WHERE "PRODUCT_NAME" LIKE 'l11b-%' AND "COACH_ID" = 'e268a512-84d6-4e27-b5c0-1d6c08a47190'
  AND "PRODUCT_CREATED_DATE" >= '2026-10-04 20:46:22.905787+00';

-- 7. coach B (cascades COACH_PARAMETERS, OFFER_PROGRAMS, MEMBER_COACHES, PRODUCTS, SESSION_SLOTS) then its user
DELETE FROM "COACHES"
WHERE "COACH_ID" = '11b00000-0000-4000-8000-0000000000b2' AND "COACH_CREATED_DATE" >= '2026-10-04 20:46:22.905787+00';
DELETE FROM "USERS"
WHERE "USER_ID" = '11b00000-0000-4000-8000-0000000000b1' AND "USER_CREATED_DATE" >= '2026-10-04 20:46:22.905787+00';

INSERT INTO l11b_counts SELECT 'after', tbl, n FROM l11b_now;

SELECT b.tbl, b.n AS before, a.n AS after FROM l11b_counts b JOIN l11b_counts a ON a.tbl = b.tbl AND a.step = 'after'
WHERE b.step = 'before' ORDER BY 1;

ROLLBACK;
